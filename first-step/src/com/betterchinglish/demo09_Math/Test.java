package com.betterchinglish.demo09_Math;

/**
 * Math 类教学示例
 * -------------------------------------------------------------
 * Math 在 java.lang 包下，无需 import，直接通过 Math.xxx() 调用。
 * 里面全是静态方法（static），所以不用 new，直接用类名调用。
 * 常用场景：取绝对值、比较大小、四舍五入、随机数、幂、开方等。
 */
public class Test {

    public static void main(String[] args) {

        /* =========================================================
         * 1. Math.abs(参数) —— 取绝对值
         *    作用：不管是正数还是负数，返回它的“非负值”
         *    入参：int / long / float / double 都可以
         *    出参：和入参同类型的绝对值
         * ========================================================= */
        int a = -10;
        System.out.println(Math.abs(a));      // 输出: 10
        double b = -3.14;
        System.out.println(Math.abs(b));      // 输出: 3.14


        /* =========================================================
         * 2. Math.max(a, b) / Math.min(a, b) —— 取最大 / 最小值
         *    作用：比较两个同类型数字，返回较大 / 较小的那个
         *    入参：两个同类型的数字（int/long/float/double）
         *    出参：两者中较大 / 较小的那个值
         * ========================================================= */
        System.out.println(Math.max(5, 8));   // 输出: 8
        System.out.println(Math.min(5, 8));   // 输出: 5


        /* =========================================================
         * 3. Math.round(小数) —— 四舍五入成 long
         *    作用：把小数按“四舍五入”规则转成最接近的整数
         *    入参：float（返回 int）或 double（返回 long）
         *    出参：四舍五入后的整数
         *    注意：.5 会向正无穷方向入，例如 -2.5 变 -2
         * ========================================================= */
        System.out.println(Math.round(3.4));  // 输出: 3
        System.out.println(Math.round(3.6));  // 输出: 4
        System.out.println(Math.round(-2.5)); // 输出: -2


        /* =========================================================
         * 4. Math.floor(小数) / Math.ceil(小数) —— 向下 / 向上取整
         *    作用：floor 取“不大于它的最大整数”，ceil 取“不小于它的最小整数”
         *    入参：double
         *    出参：double 类型的整数值
         * ========================================================= */
        System.out.println(Math.floor(3.9));  // 输出: 3.0
        System.out.println(Math.ceil(3.1));   // 输出: 4.0


        /* =========================================================
         * 5. Math.random() —— 生成 [0, 1) 之间的随机小数
         *    作用：返回一个 >=0 且 <1 的 double 随机数
         *    入参：无
         *    出参：double，范围 [0.0, 1.0)
         *    常用技巧：想生成 [0, n) 的整数，用 (int)(Math.random()*n)
         *    注意：每次运行结果都不同，所以这里只标注范围
         * ========================================================= */
        double r = Math.random();
        System.out.println(r);                 // 输出: 0.0 ~ 1.0 之间的某个小数
        int randInt = (int) (Math.random() * 10); // [0,10) 的整数
        System.out.println(randInt);           // 输出: 0 ~ 9 之间的某个整数


        /* =========================================================
         * 6. Math.pow(底数, 指数) —— 求幂
         *    作用：计算 底数 的 指数 次方
         *    入参：两个 double（底数, 指数）
         *    出参：double，计算结果
         * ========================================================= */
        System.out.println(Math.pow(2, 4));   // 输出: 16.0  （2 的 4 次方）
        System.out.println(Math.pow(3, 2));   // 输出: 9.0


        /* =========================================================
         * 7. Math.sqrt(数) —— 求平方根
         *    作用：计算一个数的算术平方根
         *    入参：double
         *    出参：double，平方根；负数会返回 NaN
         * ========================================================= */
        System.out.println(Math.sqrt(16));    // 输出: 4.0
        System.out.println(Math.sqrt(2));     // 输出: 1.4142135623730951


        /* =========================================================
         * 8. 常用常量：Math.PI / Math.E
         *    作用：直接提供圆周率和自然常数，不用自己写近似值
         * ========================================================= */
        System.out.println(Math.PI);          // 输出: 3.141592653589793
        System.out.println(Math.E);           // 输出: 2.718281828459045


        /* =========================================================
         * 综合小例子：计算半径为 5 的圆的面积  S = π * r²
         * ========================================================= */
        double radius = 5;
        double area = Math.PI * Math.pow(radius, 2);
        System.out.println(area);             // 输出: 78.53981633974483
    }
}
